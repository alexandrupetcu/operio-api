export async function create(
  fastify: FastifyInstance,
  tenantId: string,
  input: CreateAppointmentInput
) {
  // Verify project belongs to tenant (if provided)
  let project: { clientId: string | null } | null = null;
  if (input.projectId) {
    project = await fastify.prisma.project.findFirst({
      where: { id: input.projectId, tenantId },
      select: { clientId: true },
    });
    if (!project) throw fastify.httpErrors.notFound("Project not found");
  }

  // Restul id-urilor din body trebuie să fie ale firmei; echipamentul/instalația
  // și ale clientului programării, iar adresa a clientului (cel dat explicit sau
  // cel al proiectului).
  await assertClientInTenant(fastify, tenantId, input.clientId);
  await assertEmployeeInTenant(fastify, tenantId, input.employeeId);
  await assertVehicleInTenant(fastify, tenantId, input.vehicleId);
  await assertEquipmentInTenant(fastify, tenantId, input.equipmentId, input.clientId);
  await assertInstallationInTenant(fastify, tenantId, input.installationId, input.clientId);
  if (input.clientAddressId) {
    const addressOwner = input.clientId ?? project?.clientId ?? null;
    if (!addressOwner) {
      throw fastify.httpErrors.badRequest("Adresa necesită un client sau un proiect cu client");
    }
    await assertAddressOfClient(fastify, addressOwner, input.clientAddressId);
  }

  const created = await fastify.prisma.appointment.create({
    data: {
      tenantId,
      projectId: input.projectId ?? null,
      clientId: input.clientId ?? null,
      clientAddressId: input.clientAddressId ?? null,
      employeeId: input.employeeId,
      equipmentId: input.equipmentId ?? null,
      installationId: input.installationId ?? null,
      vehicleId: input.vehicleId ?? null,
      type: input.type,
      title: input.title,
      notes: input.notes,
      date: new Date(input.date),
      duration: input.duration,
    },
    include: listInclude,
  });

  await invalidateDashboardCache(tenantId);
  return { ...created, _warnings: await warningsFor(fastify, tenantId, created) };
}

/**
 * Avertismentele atașate răspunsului, ca o cheie în plus (`_warnings`) — aditivă,
 * deci parserele existente din web și mobil rămân valabile.
 *
 * Rulează DUPĂ scriere și nu poate arunca: dacă verificarea eșuează, programarea
 * rămâne salvată și pur și simplu nu se avertizează nimic.
 */
/** Verificare de suprapunere pentru formular, înainte de salvare. */
export async function checkOverlaps(
  fastify: FastifyInstance,
  tenantId: string,
  args: { employeeId: string; start: Date; duration: number | null; excludeId?: string }
): Promise<OverlapResult> {
  const settings = await getSchedulingSettings(fastify.prisma, tenantId);
  return findOverlaps(fastify, tenantId, {
    ...args,
    defaultMinutes: settings.defaultDurationMinutes,
  });
}

async function warningsFor(
  fastify: FastifyInstance,
  tenantId: string,
  appointment: { id: string; employeeId: string | null; date: Date; duration: number | null },
): Promise<{ overlap: OverlapResult } | undefined> {
  if (!appointment.employeeId) return undefined;
  try {
    const settings = await getSchedulingSettings(fastify.prisma, tenantId);
    if (!settings.warnOnOverlap) return undefined;
    const overlap = await findOverlaps(fastify, tenantId, {
      employeeId: appointment.employeeId,
      start: appointment.date,
      duration: appointment.duration,
      defaultMinutes: settings.defaultDurationMinutes,
      excludeId: appointment.id,
    });
    return overlap.hasOverlap ? { overlap } : undefined;
  } catch (err) {
    console.error("[appointments] overlap check failed:", err);
    return undefined;
  }
}

export async function update(
  fastify: FastifyInstance,
  tenantId: string,
  id: string,
  input: UpdateAppointmentInput,
  scope: ApptScope = { kind: "all" }
) {
  const appointment = await fastify.prisma.appointment.findFirst({
    // 404, nu 403: nu divulgăm existența unei programări pe care cererea nu o vede.
    where: { id, tenantId, deletedAt: null, ...apptVisibilityWhere(scope) },
  });
  if (!appointment) throw fastify.httpErrors.notFound("Appointment not found");

  // Un tehnician poate prelua o programare nerepartizată sau renunța la a lui,
  // dar nu poate pasa lucrarea unui coleg — repartizarea rămâne la coordonatori.
  if (
    scope.kind === "own" &&
    input.employeeId !== undefined &&
    input.employeeId !== null &&
    input.employeeId !== scope.employeeId
  ) {
    throw fastify.httpErrors.forbidden(
      "Doar coordonatorii pot repartiza programări altui tehnician"
    );
  }
  await assertEmployeeInTenant(fastify, tenantId, input.employeeId);

  const updated = await fastify.prisma.appointment.update({
    where: { id },
    data: {
      ...(input.title !== undefined && { title: input.title }),
      ...(input.notes !== undefined && { notes: input.notes }),
      ...(input.date !== undefined && { date: new Date(input.date) }),
      ...(input.duration !== undefined && { duration: input.duration }),
      ...(input.employeeId !== undefined && { employeeId: input.employeeId }),
      ...(input.status !== undefined && { status: input.status }),
    },
    include: listInclude,
  });

  await invalidateDashboardCache(tenantId);
  return { ...updated, _warnings: await warningsFor(fastify, tenantId, updated) };
}

export async function finalize(
  fastify: FastifyInstance,
  tenantId: string,
  id: string,
  input: FinalizeAppointmentInput,
  scope: ApptScope = { kind: "all" },
  /** Header-ul `Idempotency-Key` al cererii, dacă există. */
  idempotencyKey: string | null = null
) {
  const appointment = await fastify.prisma.appointment.findFirst({
    where: { id, tenantId, deletedAt: null, ...apptVisibilityWhere(scope) },
  });
  if (!appointment) throw fastify.httpErrors.notFound("Appointment not found");

  // O programare finalizată nu se mai finalizează o dată: s-ar dubla task-urile,
  // programările noi și documentele. Excepție: aceeași cerere retrimisă (rețea
  // căzută, dublu-tap) — recunoscută după Idempotency-Key — primește răspunsul
  // precedent. Regenerarea documentelor are ruta ei (`regenerate-documents`).
  if (appointment.status === "completed") {
    const stored = storedIdempotencyKey(appointment.completionDataJson);
    if (idempotencyKey && stored && stored === idempotencyKey) {
      return fastify.prisma.appointment.findUniqueOrThrow({ where: { id }, include: listInclude });
    }
    throw fastify.httpErrors.conflict("Programarea este deja finalizată");
  }

  if (input.outcome === "raport_complet") {
    // Gas-installation reports (revizie/verificare instalație) use the FISA flow.
    if (appointment.type === "revizie_instalatie" || appointment.type === "verificare_instalatie") {
      return finalizeInstalatie(fastify, tenantId, id, appointment, input, idempotencyKey);
    }

    // Echipamentul din body: al firmei și al clientului programării (dacă are).
    await assertEquipmentInTenant(fastify, tenantId, input.equipmentId, appointment.clientId);

    // Upload client signature to S3 if provided — BEFORE the transaction (S3 isn't
    // transactional; an orphan file on failure is harmless, a row without its file is not).
    let clientSignatureS3Key: string | null = null;
    const sigData = input.reportData.clientSignature;
    if (sigData?.signatureDataUrl) {
      try {
        clientSignatureS3Key = await uploadClientSignature(tenantId, id, sigData.signatureDataUrl);
      } catch (err) {
        console.error("[finalize] Failed to upload client signature:", err);
      }
    }

    // Replace dataUrl with S3 key in stored data (don't persist huge base64)
    const reportToStore = {
      ...input.reportData,
      clientSignature: sigData
        ? {
            signatureS3Key: clientSignatureS3Key,
            gdprConsent: sigData.gdprConsent,
            gdprConsentAt: sigData.gdprConsentAt,
            clientEmail: sigData.clientEmail,
          }
        : undefined,
      ...(idempotencyKey && { _idempotencyKey: idempotencyKey }),
    };

    const eqData = input.equipmentData;

    // All DB writes in one transaction (client, equipment, revision, appointment,
    // audit, Document rows); generation jobs are enqueued only after commit.
    const { updated, jobs } = await fastify.prisma.$transaction(async (tx) => {
      const jobs: GenerateJob[] = [];

      // Save client email if provided
      if (sigData?.clientEmail && appointment.clientId) {
        await tx.client.update({
          where: { id: appointment.clientId },
          data: { email: sigData.clientEmail },
        });
      }

      // ── Equipment: update existing or create new ──
      let equipmentId = input.equipmentId ?? appointment.equipmentId;

      if (equipmentId && eqData) {
        // Update existing equipment with installation data
        await tx.equipment.update({
          where: { id: equipmentId },
          data: {
            ...(eqData.name !== undefined && { name: eqData.name }),
            ...(eqData.internalName !== undefined && { internalName: eqData.internalName }),
            ...(eqData.serial !== undefined && { serial: eqData.serial }),
            ...(eqData.fuel !== undefined && { fuel: eqData.fuel }),
            ...(eqData.deviceType !== undefined && { deviceType: eqData.deviceType }),
            ...(eqData.power !== undefined && { power: eqData.power }),
            ...(eqData.airSupply !== undefined && { airSupply: eqData.airSupply }),
            ...(eqData.feeding !== undefined && { feeding: eqData.feeding }),
            ...(eqData.location !== undefined && { location: eqData.location }),
            ...(eqData.fuelIscir !== undefined && { fuelIscir: eqData.fuelIscir }),
            ...(eqData.deviceAge !== undefined && { deviceAge: eqData.deviceAge }),
          },
        });
      } else if (!equipmentId && appointment.clientId && eqData) {
        // Create new equipment
        const created = await tx.equipment.create({
          data: {
            clientId: appointment.clientId,
            type: "CENTRALA",
            name: eqData.name || eqData.deviceType || "Centrală",
            internalName: eqData.internalName || "Centrală",
            serial: eqData.serial,
            fuel: eqData.fuel,
            deviceType: eqData.deviceType,
            power: eqData.power,
            airSupply: eqData.airSupply,
            feeding: eqData.feeding,
            location: eqData.location,
            fuelIscir: eqData.fuelIscir,
            deviceAge: eqData.deviceAge,
          },
        });
        equipmentId = created.id;
      }

      // ── Find existing or create EquipmentRevision ──
      let revisionId = appointment.equipmentRevisionId;
      let revisionHasPdfData = false;

      if (!revisionId && equipmentId) {
        // Look for a recent revision on this equipment that is NOT yet linked to
        // an appointment (e.g. one created by email-ingestion). Excluding already-
        // linked revisions avoids a P2002 on Appointment.equipmentRevisionId (@unique)
        // when a prior appointment for the same equipment already claimed one.
        const existingRevision = await tx.equipmentRevision.findFirst({
          where: {
            equipmentId,
            createdAt: { gte: new Date(Date.now() - 7 * 24 * 3600_000) },
            appointment: { is: null },
          },
          orderBy: { createdAt: "desc" },
          select: { id: true, sourceEmailId: true, analysisData: true },
        });

        if (existingRevision) {
          revisionId = existingRevision.id;
          revisionHasPdfData = !!existingRevision.sourceEmailId;
        } else {
          // Create new PENDING revision — wait for email PDF
          const revision = await tx.equipmentRevision.create({
            data: {
              equipmentId,
              revisionDate: new Date(),
              status: "PENDING",
              location: eqData?.location ?? null,
            },
          });
          revisionId = revision.id;
        }
      } else if (revisionId) {
        // Re-edit flow — check if revision already has PDF data
        const rev = await tx.equipmentRevision.findUnique({
          where: { id: revisionId },
          select: { sourceEmailId: true },
        });
        revisionHasPdfData = !!rev?.sourceEmailId;
      }

      const updated = await tx.appointment.update({
        where: { id },
        data: {
          status: "completed",
          completedAt: new Date(),
          completionDataJson: reportToStore as unknown as Prisma.InputJsonValue,
          equipmentId,
          equipmentRevisionId: revisionId,
        },
        include: listInclude,
      });

      // Activate client on revision completion (prospect → active)
      if (appointment.clientId) {
        await tx.client.updateMany({
          where: { id: appointment.clientId, status: "PROSPECT" },
          data: { status: "ACTIVE" },
        });
      }

      // Generate ISCIR only when BOTH sources are available (manual report + PDF from email)
      // If PDF hasn't arrived yet, email-ingestion worker will trigger generation when it does
      if (revisionId && revisionHasPdfData) {
        jobs.push(...(await prepareIscirDocument(tx, tenantId, revisionId, sigData?.clientEmail ?? undefined)));
      }

      // Auto-generate GDPR document if client consented AND doesn't already have one
      if (sigData?.gdprConsent && appointment.clientId) {
        // Log GDPR consent in audit trail
        await tx.auditLog.create({
          data: {
            tenantId,
            actorUserId: null,
            entityType: "client",
            entityId: appointment.clientId,
            action: "GDPR_CONSENT",
            metadataJson: {
              appointmentId: id,
              consentAt: sigData.gdprConsentAt,
              clientEmail: sigData.clientEmail,
              signatureS3Key: clientSignatureS3Key,
              hasSignature: !!clientSignatureS3Key,
            },
          },
        });

        if (!(await hasGdprDocument(tx, tenantId, appointment.clientId))) {
          const gdprJobs = await prepareGdprDocuments(tx, tenantId, appointment.clientId, clientSignatureS3Key, id);
          jobs.push(...gdprJobs);

          if (gdprJobs.length > 0) {
            // Log GDPR document generation
            await tx.auditLog.create({
              data: {
                tenantId,
                entityType: "client",
                entityId: appointment.clientId,
                action: "GDPR_DOCUMENT_GENERATED",
                metadataJson: {
                  appointmentId: id,
                  clientEmail: sigData.clientEmail,
                },
              },
            });
          }
        } else {
          console.log(`[finalize] Client ${appointment.clientId} already has GDPR document, skipping.`);
        }
      }

      return { updated, jobs };
    }, FINALIZE_TX_OPTIONS);

    await enqueueGenerateJobs(jobs);
    await invalidateDashboardCache(tenantId);
    return updated;
  }

  // La „revenire”/„programare nouă” nu există raport; cheia se ține singură.
  const keyOnlyJson = idempotencyKey
    ? ({ _idempotencyKey: idempotencyKey } as Prisma.InputJsonValue)
    : undefined;

  if (input.outcome === "revenire") {
    await assertUserInTenant(fastify, tenantId, input.followup.assignedUserId);
    const [, completed] = await fastify.prisma.$transaction([
      fastify.prisma.task.create({
        data: {
          tenantId,
          title: input.followup.title,
          description: input.followup.description,
          taskType: "followup",
          status: "open",
          priority: input.followup.priority,
          projectId: appointment.projectId,
          clientId: appointment.clientId,
          assignedUserId: input.followup.assignedUserId,
          dueAt: input.followup.dueAt ? new Date(input.followup.dueAt) : undefined,
        },
      }),
      fastify.prisma.appointment.update({
        where: { id },
        data: { status: "completed", completedAt: new Date(), completionDataJson: keyOnlyJson },
        include: listInclude,
      }),
    ]);
    await invalidateDashboardCache(tenantId);
    return completed;
  }

  // outcome === "programare_noua"
  const [, completed] = await fastify.prisma.$transaction([
    fastify.prisma.appointment.create({
      data: {
        tenantId,
        projectId: appointment.projectId,
        clientId: appointment.clientId,
        employeeId: appointment.employeeId,
        type: input.newAppointment.type,
        title: input.newAppointment.title,
        notes: input.newAppointment.notes,
        date: new Date(input.newAppointment.date),
        duration: input.newAppointment.duration,
      },
    }),
    fastify.prisma.appointment.update({
      where: { id },
      data: { status: "completed", completedAt: new Date(), completionDataJson: keyOnlyJson },
      include: listInclude,
    }),
  ]);
  await invalidateDashboardCache(tenantId);
  return completed;
}

/**
 * Urmare după finalizare: o revenire (task) sau o programare nouă, pe o
 * programare deja finalizată — aceleași ramuri ca la `finalize`, dar starea
 * programării NU se atinge. Idempotent pe `Idempotency-Key`: cheile folosite
 * stau în `completionDataJson._followupKeys` (ultimele 20); o cheie văzută deja
 * întoarce programarea, fără alt task / altă programare. Verificarea cheii și
 * scrierea stau sub blocajul programării, ca două retrimiteri simultane să nu
 * treacă amândouă.
 */
export async function followup(
  fastify: FastifyInstance,
  tenantId: string,
  id: string,
  input: FollowupAppointmentInput,
  scope: ApptScope = { kind: "all" },
  idempotencyKey: string | null = null
) {
  const appointment = await fastify.prisma.appointment.findFirst({
    where: { id, tenantId, deletedAt: null, ...apptVisibilityWhere(scope) },
    select: { id: true, status: true, projectId: true, clientId: true, employeeId: true, completionDataJson: true },
  });
  if (!appointment) throw fastify.httpErrors.notFound("Appointment not found");
  if (appointment.status !== "completed") {
    throw fastify.httpErrors.conflict("Programarea nu este finalizată — folosește finalizarea cu rezultatul dorit");
  }
  // Drum rapid, fără tranzacție: cheia e deja consumată.
  if (idempotencyKey && storedFollowupKeys(appointment.completionDataJson).includes(idempotencyKey)) {
    return fastify.prisma.appointment.findUniqueOrThrow({ where: { id }, include: listInclude });
  }

  // FK-urile din body: ale firmei (programarea însăși e deja verificată mai sus).
  if (input.outcome === "revenire") {
    await assertUserInTenant(fastify, tenantId, input.followup.assignedUserId);
  }

  const result = await fastify.prisma.$transaction(async (tx) => {
    await lockKey(tx, `appointment:${id}`);
    const fresh = await tx.appointment.findUniqueOrThrow({ where: { id }, select: { completionDataJson: true } });
    const usedKeys = storedFollowupKeys(fresh.completionDataJson);
    if (idempotencyKey && usedKeys.includes(idempotencyKey)) {
      return tx.appointment.findUniqueOrThrow({ where: { id }, include: listInclude });
    }

    if (input.outcome === "revenire") {
      await tx.task.create({
        data: {
          tenantId,
          title: input.followup.title,
          description: input.followup.description,
          taskType: "followup",
          status: "open",
          priority: input.followup.priority,
          projectId: appointment.projectId,
          clientId: appointment.clientId,
          assignedUserId: input.followup.assignedUserId,
          dueAt: input.followup.dueAt ? new Date(input.followup.dueAt) : undefined,
        },
      });
    } else {
      await tx.appointment.create({
        data: {
          tenantId,
          projectId: appointment.projectId,
          clientId: appointment.clientId,
          employeeId: appointment.employeeId,
          type: input.newAppointment.type,
          title: input.newAppointment.title,
          notes: input.newAppointment.notes,
          date: new Date(input.newAppointment.date),
          duration: input.newAppointment.duration,
        },
      });
    }

    // Raportul (sau `{ _idempotencyKey }`) rămâne neatins; doar lista de chei crește.
    if (!idempotencyKey) {
      return tx.appointment.findUniqueOrThrow({ where: { id }, include: listInclude });
    }
    const base =
      fresh.completionDataJson && typeof fresh.completionDataJson === "object" && !Array.isArray(fresh.completionDataJson)
        ? (fresh.completionDataJson as Record<string, unknown>)
        : {};
    const keys = [...usedKeys, idempotencyKey].slice(-FOLLOWUP_KEYS_MAX);
    return tx.appointment.update({
      where: { id },
      data: { completionDataJson: { ...base, _followupKeys: keys } as Prisma.InputJsonValue },
      include: listInclude,
    });
  }, FINALIZE_TX_OPTIONS);

  await invalidateDashboardCache(tenantId);
  return result;
}

export async function remove(
  fastify: FastifyInstance,
  tenantId: string,
  id: string,
  scope: ApptScope = { kind: "all" }
) {
  const appointment = await fastify.prisma.appointment.findFirst({
    where: { id, tenantId, deletedAt: null, ...apptVisibilityWhere(scope) },
  });
  if (!appointment) throw fastify.httpErrors.notFound("Appointment not found");

  // Soft delete
  return fastify.prisma.appointment.update({
    where: { id },
    data: { deletedAt: new Date() },
  });
}

export async function restore(
  fastify: FastifyInstance,
  tenantId: string,
  id: string
) {
  const appointment = await fastify.prisma.appointment.findFirst({
    where: { id, tenantId, deletedAt: { not: null } },
  });
  if (!appointment) throw fastify.httpErrors.notFound("Archived appointment not found");

  return fastify.prisma.appointment.update({
    where: { id },
    data: { deletedAt: null },
    include: listInclude,
  });
}

export async function listArchived(
  fastify: FastifyInstance,
  tenantId: string,
  projectId?: string
) {
  return fastify.prisma.appointment.findMany({
    where: { tenantId, deletedAt: { not: null }, ...(projectId && { projectId }) },
    include: listInclude,
    orderBy: { deletedAt: "desc" },
    take: 500,
  });
}
