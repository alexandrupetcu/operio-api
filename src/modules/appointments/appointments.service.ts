/**
 * `completionDataJson` ține raportul la `raport_complet`; la celelalte rezultate
 * ține doar cheia de idempotență (`{ _idempotencyKey }`). Cititorii de raport
 * (regenerare, prefill) trebuie să deosebească cele două forme.
 */
function hasInstalatieReport(json: unknown): json is InstalatieReportData {
  return !!json && typeof json === "object" && "decizie" in (json as Record<string, unknown>);
}

/** Cheia trimisă de client la finalizare, dacă a fost stocată. */
function storedIdempotencyKey(json: unknown): string | null {
  if (!json || typeof json !== "object") return null;
  const k = (json as Record<string, unknown>)._idempotencyKey;
  return typeof k === "string" ? k : null;
}

/** Cheile `Idempotency-Key` deja folosite pe `/followup` (`completionDataJson._followupKeys`). */
const FOLLOWUP_KEYS_MAX = 20;
function storedFollowupKeys(json: unknown): string[] {
  if (!json || typeof json !== "object" || Array.isArray(json)) return [];
  const keys = (json as Record<string, unknown>)._followupKeys;
  return Array.isArray(keys) ? keys.filter((k): k is string => typeof k === "string") : [];
}

const documentQueue = new Queue("document-generation", { connection: redisConnection, defaultJobOptions });

/** Client Prisma obișnuit sau cel dintr-o tranzacție interactivă. */
type Db = PrismaClient | Prisma.TransactionClient;

/**
 * Job de generare pregătit în baza de date, dar încă nepus în coadă. Finalizarea
 * scrie rândurile Document în tranzacție și pune joburile în coadă abia după
 * commit — altfel worker-ul ar putea lua un document pe care tranzacția l-a
 * retras între timp.
 */
type GenerateJob = {
  documentId: string;
  tenantId: string;
  clientId: string;
  templateId: string;
  revisionId?: string;
};

async function enqueueGenerateJobs(jobs: GenerateJob[]): Promise<void> {
  for (const job of jobs) {
    await documentQueue.add("generate", job);
  }
}

/** Tranzacțiile de finalizare fac 8–12 scrieri; 5 s (implicitul Prisma) e prea strâns sub încărcare. */
const FINALIZE_TX_OPTIONS = { maxWait: 5_000, timeout: 20_000 } as const;

async function uploadClientSignature(
  tenantId: string,
  appointmentId: string,
  dataUrl: string
): Promise<string> {
  const match = dataUrl.match(/^data:image\/(png|jpeg);base64,(.+)$/);
  if (!match) throw new Error("Invalid signature data URL");
  const buffer = Buffer.from(match[2], "base64");
  const ext = match[1];
  const s3Key = `${tenantId}/signatures/client/${appointmentId}.${ext}`;
  await uploadFile(s3Key, buffer, `image/${ext}`);
  return s3Key;
}

/**
 * Creează rândurile Document pentru acordul GDPR (auto) și întoarce joburile de
 * generare — apelantul le pune în coadă după commit.
 */
async function prepareGdprDocuments(
  db: Db,
  tenantId: string,
  clientId: string,
  clientSignatureS3Key: string | null,
  /** Programarea la care s-a semnat acordul — ca să apară în documentele ei din Calendar. */
  appointmentId: string
): Promise<GenerateJob[]> {
  const templates = await db.documentTemplate.findMany({
    where: {
      categoryCode: "GDPR",
      OR: [{ tenantId }, { tenantId: null }],
      isActive: true,
    },
  });
  if (templates.length === 0) return [];

  const jobs: GenerateJob[] = [];
  for (const template of templates) {
    const document = await db.document.create({
      data: {
        tenantId,
        templateId: template.id,
        name: `Acord GDPR - auto`,
        status: "PENDING",
        appointmentId,
        clients: { create: { clientId } },
        contextJson: clientSignatureS3Key
          ? ({ clientSignatureS3Key, gdprAutoGenerated: true } as Prisma.InputJsonValue)
          : ({ gdprAutoGenerated: true } as Prisma.InputJsonValue),
      },
    });
    jobs.push({ documentId: document.id, tenantId, clientId, templateId: template.id });
  }
  return jobs;
}

/**
 * Pregătește (sau resetează la PENDING) documentul ISCIR al unei revizii de
 * centrală și întoarce jobul de generare — pus în coadă de apelant după commit.
 */
async function prepareIscirDocument(
  db: Db,
  tenantId: string,
  revisionId: string,
  sendToEmail?: string,
  /** Înlocuiește `contextJson` (ex. regenerarea după înregistrarea la OS). */
  replaceCtx?: Record<string, unknown>,
): Promise<GenerateJob[]> {
  // Find the revision and its equipment/client
  const revision = await db.equipmentRevision.findUnique({
    where: { id: revisionId },
    include: { equipment: { include: { client: true } } },
  });
  if (!revision) return [];
  const clientId = revision.equipment.clientId;

  const iscirTemplate = await db.documentTemplate.findFirst({
    where: {
      categoryCode: "REVIZIE_CENTRALA",
      OR: [{ tenantId }, { tenantId: null }],
      isActive: true,
    },
  });
  if (!iscirTemplate) return [];

  // Reuse existing document if one is already linked to this revision
  let documentId = revision.iscirDocumentId;

  const ctxJson = replaceCtx
    ? (replaceCtx as Prisma.InputJsonValue)
    : sendToEmail
      ? ({ sendToEmail } as Prisma.InputJsonValue)
      : undefined;

  if (documentId) {
    await db.document.update({
      where: { id: documentId },
      data: {
        status: "PENDING",
        s3Key: null,
        errorMessage: null,
        ...(ctxJson && { contextJson: ctxJson }),
      },
    });
  } else {
    const document = await db.document.create({
      data: {
        tenantId,
        templateId: iscirTemplate.id,
        name: `Revizie ${revision.equipment.name ?? ""} - ${new Date().toLocaleDateString("ro-RO")}`.trim(),
        status: "PENDING",
        clients: { create: { clientId } },
        contextJson: ctxJson,
      },
    });
    documentId = document.id;
    await db.equipmentRevision.update({
      where: { id: revision.id },
      data: { iscirDocumentId: documentId },
    });
  }

  return [{ documentId, tenantId, clientId, templateId: iscirTemplate.id, revisionId: revision.id }];
}

/**
 * După înregistrarea reviziei de centrală la OS: regenerează raportul ISCIR (caseta
 * „Înregistrat la” primește distribuitorul și numărul) și, dacă `notifyClient`,
 * worker-ul trimite clientului exemplarul cu numărul. Fără e-mailul generic de la
 * finalizare (`sendToEmail` nu se păstrează).
 */
export async function regenerateIscirForOsRegistration(
  fastify: FastifyInstance,
  tenantId: string,
  appointmentId: string,
  notifyClient: boolean,
): Promise<{ queued: boolean }> {
  const appointment = await fastify.prisma.appointment.findFirst({
    where: { id: appointmentId, tenantId },
    select: { id: true, equipmentRevisionId: true },
  });
  if (!appointment?.equipmentRevisionId) return { queued: false };
  const jobs = await prepareIscirDocument(fastify.prisma, tenantId, appointment.equipmentRevisionId, undefined, {
    appointmentId: appointment.id,
    osRegistrationNotify: notifyClient,
  });
  if (!jobs.length) return { queued: false };
  await enqueueGenerateJobs(jobs);
  return { queued: true };
}

